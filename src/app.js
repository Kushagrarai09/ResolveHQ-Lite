const express=require("express");
const cors=require("cors");
const helmet=require("helmet");
const rateLimit=require("express-rate-limit");
const swaggerUi=require("swagger-ui-express");
const authRoutes=require("./routes/auth");
const ticketRoutes=require("./routes/tickets");
const analyticsRoutes=require("./routes/analytics");
const notificationRoutes=require("./routes/notifications");
const userRoutes=require("./routes/users");
const uploadRoutes=require("./routes/uploads");
const openapi=require("./openapi");
const {notFound,errorHandler}=require("./middleware/errors");
const app=express();
app.disable("x-powered-by");app.use(helmet());
const allowedOrigins=(process.env.CLIENT_URL||"http://localhost:5173").split(",").map(v=>v.trim()).filter(Boolean);
app.use(cors({origin(origin,callback){if(!origin||allowedOrigins.includes(origin))return callback(null,true);return callback(new Error("Origin is not allowed by CORS."));}}));
app.use(express.json({limit:"1mb"}));
app.use("/api",rateLimit({windowMs:15*60*1000,limit:300,standardHeaders:"draft-7",legacyHeaders:false}));
app.use("/api/auth",rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:"draft-7",legacyHeaders:false}));
app.get("/",(req,res)=>res.json({success:true,name:"ResolveHQ Lite API",message:"Support ticket REST API is running.",docs:"/api-docs"}));
app.get("/health",(req,res)=>res.json({success:true,status:"ok"}));
app.use("/api-docs",swaggerUi.serve,swaggerUi.setup(openapi));
app.use("/api/auth",authRoutes);app.use("/api/tickets",ticketRoutes);app.use("/api/analytics",analyticsRoutes);
app.use("/api/notifications",notificationRoutes);app.use("/api/users",userRoutes);app.use("/api/uploads",uploadRoutes);
app.use(notFound);app.use(errorHandler);
module.exports=app;
